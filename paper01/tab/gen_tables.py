"""Emit the LaTeX table bodies of Section 5 straight from the experiment CSVs.

Every number quoted in the paper's experimental section comes from here, so a
re-run of the batch followed by a re-run of this script updates the paper
without anybody retyping a figure.  The fragments are \\input{} from paper.tex
and contain table *bodies* only: the surrounding tabular, caption and label stay
in the paper where they can be read alongside the prose.

    cd clbs && py -m tools.export_experiments --runs p3 lowmid --gen-runs gen100
    cd paper01_new/tab && py gen_tables.py
"""
from __future__ import annotations

import csv
import os
import statistics as st
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
CLBS = os.path.join(ROOT, "clbs")
DATA = os.path.join(CLBS, "experiments")
if CLBS not in sys.path:
    sys.path.insert(0, CLBS)

from algorithm.stats import wilcoxon_signed_rank  # noqa: E402

TAGS = ["low", "mid", "high", "funnel"]
TAG_TEX = {"low": r"\texttt{low}", "mid": r"\texttt{mid}",
           "high": r"\texttt{high}", "funnel": r"\texttt{funnel}"}

# 论文正文里的档位名;顺序按每次评价的成本从低到高,好让"越贵越差"一眼可见
ARM_TEX = {
    "twostage":          "two-stage (surrogate transport)",
    "opendispatch_nols": r"\textbf{evaluation loop} (proposed)",
    "opendispatch":      "+ contention-guided search",
    "nofeedback":        "+ reservation-aware dispatch",
    "nostagger":         "+ both, without staggering",
    "closed":            "+ both (full closed loop)",
    "priced":            "+ priced routing (control)",
}
ARM_ORDER = ["twostage", "opendispatch_nols", "opendispatch", "nofeedback",
             "nostagger", "closed", "priced"]

REF = "opendispatch_nols"      # 主方法:最小内核

# 消融表:每行只差一个因素。(机制, 上下文, 关掉的档, 开着的档)
CONTRASTS = [
    ("Conflict-free routing in the loop", "cheap dispatch",
     "twostage", "opendispatch_nols"),
    ("Conflict-free routing in the loop", "exact dispatch",
     "twostage", "nofeedback"),
    ("Reservation-aware dispatch", "no local search",
     "opendispatch_nols", "nofeedback"),
    ("Reservation-aware dispatch", "with local search",
     "opendispatch", "closed"),
    ("Contention-guided local search", "cheap dispatch",
     "opendispatch_nols", "opendispatch"),
    ("Contention-guided local search", "exact dispatch",
     "nofeedback", "closed"),
    ("Staggering operator", "on top of reassignment",
     "nostagger", "closed"),
    ("Priced routing", "on top of the full loop", "closed", "priced"),
]


def load(name):
    with open(os.path.join(DATA, name), encoding="utf-8") as f:
        return list(csv.DictReader(f))


def stars(p):
    """显著性星号。返回的是数学模式内的上标,故调用处须已在 $...$ 里。"""
    return "^{***}" if p < 1e-3 else "^{**}" if p < 1e-2 \
        else "^{*}" if p < 5e-2 else ""


def fmt_p(p):
    if p < 1e-4:
        return "$<10^{-4}$"
    if p >= 1e-3:
        return "%.3f" % p
    mant, exp = ("%.0e" % p).split("e")
    return r"$%s\times10^{%d}$" % (mant, int(exp))


def write(name, colspec, header, body):
    """写出**完整的** tabular 片段。

    片段必须自带 tabular 而不能只给表体:在 tabular 内部 \\input 一段以 `\\\\`
    结尾的文件会崩,因为 `\\\\` 需要向前扫描可选的 `[len]` 参数,而这个扫描跨不过
    文件边界,于是紧随的 \\bottomrule(展开为 \\noalign)不再紧接 \\cr。
    连带的好处是列格式与表头和生成表体待在一处,不会再各自漂移出列数不符。
    """
    path = os.path.join(HERE, name)
    lines = ["%% generated by tab/gen_tables.py -- do not edit by hand",
             r"\begin{tabular}{%s}" % colspec,
             r"\toprule",
             header.rstrip().rstrip("\\") + r" \\",
             r"\midrule",
             body.rstrip(),
             r"\bottomrule",
             r"\end{tabular}"]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(path, ROOT))


