def table_instances(feats):
    """按拥堵档聚合:结构指标只取决于拥堵档,下界随 H 变,故给区间。"""
    rows = []
    for tag in TAGS:
        sub = [f for f in feats if f["congestion_tag"] == tag]
        if not sub:
            continue

        def uniq(key, cast=float):
            vals = sorted({cast(f[key]) for f in sub})
            return vals

        phi, cut, far = uniq("funnel_share"), uniq("lu_min_cut"), \
            uniq("far_group_cut")
        lb = uniq("lower_bound")
        nv, ne = uniq("num_nodes"), uniq("num_corridors")
        # 绑定项:三个下界分量里取到最大值的那个
        bind = set()
        for f in sub:
            terms = {"job chain": float(f["job_chain"]),
                     "machine load": float(f["machine_load"]),
                     "station cut": float(f["lu_cut"])}
            bind.add(max(terms, key=terms.get))

        def rng(vals, fmt="%.2f"):
            if len(vals) == 1:
                return fmt % vals[0]
            return (fmt + "--" + fmt) % (vals[0], vals[-1])

        rows.append(" & ".join([
            TAG_TEX[tag], rng(nv, "%.0f"), rng(ne, "%.0f"),
            rng(cut, "%.0f"), rng(far, "%.0f"), rng(phi),
            rng(lb, "%.1f"), ", ".join(sorted(bind)),
        ]) + r" \\")
    return "\n".join(rows)


def table_main(runs):
    """各档相对两阶段的收益,并列出每次评价的成本与实际完成的评价次数。"""
    idx = defaultdict(dict)
    for r in runs:
        idx[(r["instance"], r["seed"])][r["arm"]] = r
    cost, evals = defaultdict(list), defaultdict(list)
    for r in runs:
        if r.get("ms_per_eval"):
            cost[r["arm"]].append(float(r["ms_per_eval"]))
        if r.get("evaluations"):
            evals[r["arm"]].append(float(r["evaluations"]))

    rows = []
    for arm in ARM_ORDER:
        c = "%.2f" % st.mean(cost[arm]) if cost.get(arm) else "---"
        e = "%.0f" % st.mean(evals[arm]) if evals.get(arm) else "---"
        if arm == "twostage":
            rows.append(" & ".join([ARM_TEX[arm], c, e, "---", "---", "---"])
                        + r" \\")
            rows.append(r"\midrule")
            continue
        pairs = [(float(v["twostage"]["makespan"]), float(v[arm]["makespan"]))
                 for v in idx.values() if "twostage" in v and arm in v]
        g = 100 * st.mean([(a - b) / a for a, b in pairs if a > 0])
        w = wilcoxon_signed_rank([a for a, _ in pairs], [b for _, b in pairs])
        wins = sum(1 for a, b in pairs if b < a)
        loss = sum(1 for a, b in pairs if b > a)
        rows.append(" & ".join([
            ARM_TEX[arm], c, e,
            "$%+.2f%s$" % (g, stars(w["p_value"])),
            "%d/%d/%d" % (wins, loss, len(pairs) - wins - loss),
            fmt_p(w["p_value"]),
        ]) + r" \\")
    return "\n".join(rows)


def table_ablation(runs):
    """可归因的消融:每行只差一个因素,同一机制给两个上下文以便交叉核对。"""
    idx = defaultdict(dict)
    for r in runs:
        idx[(r["instance"], r["seed"])][r["arm"]] = r
    cost = defaultdict(list)
    for r in runs:
        if r.get("ms_per_eval"):
            cost[r["arm"]].append(float(r["ms_per_eval"]))

    rows, prev = [], None
    for mech, ctx, off, on in CONTRASTS:
        pairs = [(float(v[off]["makespan"]), float(v[on]["makespan"]))
                 for v in idx.values() if off in v and on in v]
        if not pairs:
            continue
        g = 100 * st.mean([(a - b) / a for a, b in pairs if a > 0])
        w = wilcoxon_signed_rank([a for a, _ in pairs], [b for _, b in pairs])
        wins = sum(1 for a, b in pairs if b < a)
        loss = sum(1 for a, b in pairs if b > a)
        ratio = st.mean(cost[on]) / st.mean(cost[off]) if cost.get(off) else 0
        if prev is not None and prev != mech:
            rows.append(r"\addlinespace")
        name = mech if prev != mech else ""
        prev = mech
        rows.append(" & ".join([
            name, ctx, r"$%.1f\times$" % ratio,
            "$%+.2f%s$" % (g, stars(w["p_value"])),
            "%d/%d/%d" % (wins, loss, len(pairs) - wins - loss),
            fmt_p(w["p_value"]),
        ]) + r" \\")
    return "\n".join(rows)


def table_bytag(runs):
    """主方法相对两阶段的收益,按拥堵档与异构度分层——用于'收益是否随拥堵上升'。"""
    idx = defaultdict(dict)
    for r in runs:
        idx[(r["instance"], r["seed"])][r["arm"]] = r
    rows = []
    for tag in TAGS:
        cells = []
        for het in ["0.0", "0.15", "0.3", "0.5"]:
            pairs = [(float(v["twostage"]["makespan"]), float(v[REF]["makespan"]))
                     for (i, _s), v in idx.items()
                     if "twostage" in v and REF in v
                     and v[REF]["tag"] == tag
                     and str(float(v[REF]["het"] or 0)) == het]
            cells.append("$%+.1f$" % (100 * st.mean(
                [(a - b) / a for a, b in pairs if a > 0])) if pairs else "---")
        pooled = [(float(v["twostage"]["makespan"]), float(v[REF]["makespan"]))
                  for v in idx.values()
                  if "twostage" in v and REF in v and v[REF]["tag"] == tag]
        w = wilcoxon_signed_rank([a for a, _ in pooled], [b for _, b in pooled])
        rows.append(" & ".join(
            [TAG_TEX[tag]] + cells
            + ["$%+.2f%s$" % (100 * st.mean([(a - b) / a for a, b in pooled
                                             if a > 0]), stars(w["p_value"]))]
        ) + r" \\")
    return "\n".join(rows)


def main() -> int:
    runs = load("runs.csv")
    feats = load("instances.csv")

    write("tab_instances.tex", "@{}lccccrrl@{}",
          r"Structure & $|V|$ & $|E|$ & cut & far cut & $\varphi$ & LB "
          r"& binding term",
          table_instances(feats))

    write("tab_main.tex", "@{}lrrrcr@{}",
          r"Configuration & ms/eval & evals & $\Delta C_{\max}$ (\%) "
          r"& W/L/T & $p$",
          table_main(runs))

    write("tab_ablation.tex", "@{}llrrcr@{}",
          r"Mechanism & Context & Cost & $\Delta C_{\max}$ (\%) & W/L/T & $p$",
          table_ablation(runs))

    write("tab_bytag.tex", "@{}lccccc@{}",
          r"& \multicolumn{4}{c}{$\Delta C_{\max}$ (\%) at $H=$} & pooled \\"
          "\n" r"\cmidrule(lr){2-5}" "\n"
          r"Structure & $0$ & $0.15$ & $0.3$ & $0.5$ & (\%)",
          table_bytag(runs))

    n_inst = len({r["instance"] for r in runs})
    n_seed = len({r["seed"] for r in runs})
    print("scope: %d instances x %d seeds, %d runs"
          % (n_inst, n_seed, len(runs)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
