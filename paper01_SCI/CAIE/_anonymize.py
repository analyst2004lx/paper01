# Derive a self-contained anonymized manuscript from paper01_CAIE.tex.
# The source itself must carry no author data, since the review PDF is built from it.
import io, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
src = io.open(os.path.join(HERE, "paper01_CAIE.tex"), encoding="utf-8").read()

out = src
out = out.replace(r"\documentclass[preprint,review,12pt,authoryear]{elsarticle}",
                  r"\documentclass[preprint,review,12pt,authoryear,doubleblind]{elsarticle}", 1)
out = re.sub(r"\n\\author\[.*?(?=\n\\begin\{abstract\})", "\n", out, count=1, flags=re.S)
out = re.sub(r"\n% elsarticle prints author names.*?\\end\{highlights\}\n\\fi\n", "\n", out, count=1, flags=re.S)
out = re.sub(r"\n%\\section\*\{Acknowledgments\}\n%[^\n]*", "", out)
out = re.sub(r"^%% file; this file \(with authors\) serves as the title-page version\.\n", "", out, flags=re.M)

for pat in [r"\\author", r"\\ead", r"\\affiliation", r"Southeast", r"seu\.edu", r"Qi Yu", r"Wei Li",
            r"highlights", r"Acknowledg"]:
    assert not re.search(pat, out), pat
assert "doubleblind]" in out

io.open(os.path.join(HERE, "paper01_CAIE_anonymized.tex"), "w", encoding="utf-8", newline="\n").write(
    "%% Anonymized manuscript for double-anonymized review (generated by _anonymize.py).\n" + out)
print("written paper01_CAIE_anonymized.tex")
